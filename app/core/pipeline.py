"""Personal Assistant end-to-end pipeline orchestrator.

This module coordinates the complete voice interaction lifecycle:
1. Audio input ingestion and resampling.
2. OpenVINO Whisper Base INT8 speech-to-text transcription.
3. LM Studio local LLM conversational reasoning (token streaming).
4. Sentence-by-sentence chunking with abbreviation/decimal protection.
5. Kokoro-82M expressive speech synthesis pipelined concurrently with LLM generation.
6. Seamless sequential audio playback via StreamAudioPlayer.
"""

